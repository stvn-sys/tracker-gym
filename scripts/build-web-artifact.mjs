// Builds a self-locating copy of the web export that runs from any URL path
// (e.g. a hosted preview page), without server rewrites or special headers.
//
//   EXPO_OFFLINE=1 npx expo export -p web && node scripts/build-web-artifact.mjs <outDir>
//
// What it does:
//  - copies dist/ to <outDir>, renaming files with [brackets] in their names
//  - replaces absolute "/_expo/..." and "/assets/..." URLs with ones computed at
//    runtime from where boot.js was loaded (window.__TG_BASE), and inside the
//    SQLite worker from the worker's own URL
//  - writes boot.js (finds the base URL, resets the router path to "/", then loads
//    the bundles) and index.html (the page shell)
import fs from 'node:fs';
import path from 'node:path';

const src = 'dist';
const out = process.argv[2];
if (!out) throw new Error('usage: node scripts/build-web-artifact.mjs <outDir>');
fs.rmSync(out, { recursive: true, force: true });

const files = [];
(function walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p);
    else files.push(path.relative(src, p));
  }
})(src);

// Hosts may reserve names starting with "_" or reject brackets, so flatten paths:
// "_expo/static/js/web/__common-x.js" -> "js/common-x.js", "[id]-x.js" -> "id-x.js".
const safe = (rel) => rel
  .replace(/^_expo\/static\/js\/web\//, 'js/')
  .replace(/\[|\]/g, '')
  .replace(/(^|\/)_+/g, '$1');
const renames = files.filter((f) => f !== safe(f));

for (const rel of files) {
  if (rel === 'index.html' || rel === 'metadata.json' || rel === 'favicon.ico') continue;
  const dest = path.join(out, safe(rel));
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  if (!rel.endsWith('.js')) { fs.copyFileSync(path.join(src, rel), dest); continue; }
  let code = fs.readFileSync(path.join(src, rel), 'utf8');
  for (const r of renames) code = code.split('/' + r).join('/' + safe(r));
  if (path.basename(rel).startsWith('worker-')) {
    const workerBase = 'self.location.href.replace(/js\\/[^\\/]*$/,"")';
    code = code.replace(/"\/assets\//g, `${workerBase}+"assets/`);
  } else {
    code = code.replace(/"\/(js|assets)\//g, '(self.__TG_BASE||"/")+"$1/');
  }
  fs.writeFileSync(dest, code);
}

const html = fs.readFileSync(path.join(src, 'index.html'), 'utf8');
const bundles = [...html.matchAll(/<script src="\/([^"]+)"/g)].map((m) => safe(m[1]));

fs.writeFileSync(path.join(out, 'boot.js'), `// Generated by scripts/build-web-artifact.mjs
(function () {
  var base = document.currentScript.src.replace(/boot\\.js(\\?.*)?$/, '');
  window.__TG_BASE = base;
  // The app's router reads the URL path; start it at the home screen.
  try { history.replaceState(history.state, '', '/'); } catch (e) {}
  ${JSON.stringify(bundles)}.forEach(function (f) {
    var s = document.createElement('script');
    s.src = base + f;
    s.async = false;
    document.body.appendChild(s);
  });
})();
`);

fs.writeFileSync(path.join(out, 'index.html'), `<title>Tracker Gym</title>
<meta name="theme-color" content="#0B0D17">
<style>
  :root { color-scheme: dark; --bg: #0B0D17; --fg: #F2F4FF; }
  html, body { height: 100%; }
  body { overflow: hidden; background: var(--bg); color: var(--fg); }
  #root { display: flex; height: 100%; flex: 1; }
</style>
<div id="root"></div>
<script src="boot.js"></script>
`);
console.log(`wrote ${out}: ${bundles.length} bundles, ${renames.length} renamed files`);
